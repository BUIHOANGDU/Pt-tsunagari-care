  function normalizeLanguage(language) {
    return SUPPORTED_LANGUAGES.has(language) ? language : DEFAULT_LANGUAGE;
  }

  function getCurrentLanguage() {
    return normalizeLanguage(localStorage.getItem(STORAGE_KEY) || DEFAULT_LANGUAGE);
  }

  function t(key) {
    const language = getCurrentLanguage();
    return translations[language]?.[key] ?? translations.ja[key] ?? key;
  }

  function applyTranslations(root = document) {
    const language = getCurrentLanguage();
    document.documentElement.lang = language;
    document.title = t("pageTitle");

    root.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute(
        "aria-label",
        t(element.getAttribute("data-i18n-aria-label")),
      );
    });
    root.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", t(element.getAttribute("data-i18n-title")));
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute(
        "placeholder",
        t(element.getAttribute("data-i18n-placeholder")),
      );
    });
    root.querySelectorAll("[data-language-option]").forEach((element) => {
      const active = element.getAttribute("data-language-option") === language;
      element.classList.toggle("is-active", active);
      element.setAttribute("aria-pressed", active ? "true" : "false");
    });
  }

  function setLanguage(language) {
    const nextLanguage = normalizeLanguage(language);
    localStorage.setItem(STORAGE_KEY, nextLanguage);
    applyTranslations();
    window.dispatchEvent(
      new CustomEvent("tsunagari-language-change", {
        detail: { language: nextLanguage },
      }),
    );
    return nextLanguage;
  }

  window.TsunagariI18n = {
    t,
    setLanguage,
    getCurrentLanguage,
    applyTranslations,
  };
  window.t = t;
  window.setLanguage = setLanguage;
  window.getCurrentLanguage = getCurrentLanguage;
  window.applyTranslations = applyTranslations;

  document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    document.querySelectorAll("[data-language-option]").forEach((button) => {
      button.addEventListener("click", () => {
        setLanguage(button.getAttribute("data-language-option"));
      });
    });
  });
